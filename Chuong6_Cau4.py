# Khai báo danh sách và biến x
lst = [3, 0, 1, 5, 2]
x = 2

# In kết quả từng phần
print("(a) lst[0] =", lst[0])
print("(b) lst[3] =", lst[3])
print("(c) lst[x] =", lst[x])
print("(d) lst[-x] =", lst[-x])
print("(e) lst[x + 1] =", lst[x + 1])
print("(f) lst[x] + 1 =", lst[x] + 1)
print("(g) lst[lst[x]] =", lst[lst[x]])
print("(h) lst[lst[lst[x]]] =", lst[lst[lst[x]]])
